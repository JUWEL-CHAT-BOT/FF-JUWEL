const BN_DIGITS = ["০", "১", "২", "৩", "৪", "৫", "৬", "৭", "৮", "৯"];
const bnNum = (n) => String(n).replace(/\d/g, (d) => BN_DIGITS[Number(d)]);
const enNum = (s) => String(s).replace(/[০-৯]/g, (d) => BN_DIGITS.indexOf(d));

// বাংলা ড়/ঢ়/য় এর দুই ধরনের এনকোডিং এক করে + ছোট হাতের + চিহ্ন/স্পেস বাদ
function norm(s) {
  return String(s == null ? "" : s)
    .normalize("NFC")
    .replace(/ড়/g, "ড়")
    .replace(/ঢ়/g, "ঢ়")
    .replace(/য়/g, "য়")
    .toLowerCase()
    .replace(/['’`\-.,\s()]/g, "")
    .replace(/(জেলা|বিভাগ|district|division|zila|jela)$/i, "");
}

const TOTAL_DISTRICTS = DIVISIONS.reduce((n, d) => n + d.districts.length, 0);
