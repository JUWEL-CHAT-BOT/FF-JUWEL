function distReply(div, dist) {
  return { type: "district", div: DIVISIONS.indexOf(div), dist: div.districts.indexOf(dist) };
}
function divReply(div) {
  return { type: "division", div: DIVISIONS.indexOf(div) };
}

function districtAnswer(div, dist, withDivision) {
  const body =
    "🗺️ ম্যাপস: " + dist[1] + " জেলা\n" + LINE + "\n" +
    tree(div, dist) + "\n" +
    districtBlock(dist) + "\n\n" +
    (withDivision ? divisionBlock(div, dist) + "\n" : "") +
    "🧭 জেলার ম্যাপ: " + mapLink(dist[0] + " District");
  return { msg: body, reply: distReply(div, dist) };
}

function divisionAnswer(div) {
  return {
    msg:
      "🗺️ ম্যাপস: " + div.bn + " বিভাগ\n" + LINE + "\n" +
      tree(div, null) + "\n" +
      divisionBlock(div, null) + "\n" +
      "👉 জেলার নম্বর রিপ্লাই দিন\n🧭 বিভাগের ম্যাপ: " + mapLink(div.en + " Division"),
    reply: divReply(div)
  };
}

function placeAnswer(hits) {
  if (hits.length === 1) {
    const h = hits[0];
    return { msg: placeCard(h.name, h.dist, h.div) + "\n\n" + tree(h.div, h.dist), reply: null };
  }
  let t = "📌 " + bnNum(hits.length) + "টি জায়গা পাওয়া গেছে:\n" + LINE + "\n";
  hits.slice(0, 6).forEach((h, i) => {
    t += bnNum(i + 1) + ". " + h.name + " (" + h.dist[1] + ")\n🧭 " + placeLink(h.name, h.dist, h.div) + "\n\n";
  });
  if (hits.length > 6) t += "… আরও " + bnNum(hits.length - 6) + "টি। আরো নির্দিষ্ট নাম লিখুন।";
  return { msg: t.trim(), reply: null };
}

function findDistrict(q) {
  return distIndex.find((x) => x.keys.includes(q));
}

function buildAnswer(query) {
  const q = norm(query);
  if (!q) return { msg: overview(), reply: { type: "overview" } };

  const divHit = divIndex.find((x) => x.keys.includes(q));
  const distHit = findDistrict(q);

  // বিভাগ ও জেলা একই নাম (যেমন রংপুর) → দুটোই দেখাবে
  if (divHit && distHit && distHit.div === divHit.d) return districtAnswer(distHit.div, distHit.dist, true);
  if (distHit) return districtAnswer(distHit.div, distHit.dist, true);
  if (divHit) return divisionAnswer(divHit.d);

  // জায়গার নাম মিলিয়ে দেখি (পুরো মিল আগে, তারপর আংশিক)
  if (q.length >= 2) {
    const exact = placeIndex.filter((p) => p.key === q);
    if (exact.length) return placeAnswer(exact);
    const part = placeIndex.filter((p) => p.key.includes(q));
    if (part.length) return placeAnswer(part);
  }

  // সরাসরি না মিললে কাছাকাছি নাম খুঁজি
  if (q.length >= 2) {
    const names = [];
    divIndex.forEach((x) => {
      if (x.keys.some((k) => k.includes(q) || q.includes(k))) names.push(x.d.bn + " (বিভাগ)");
    });
    distIndex.forEach((x) => {
      if (x.keys.some((k) => k.includes(q) || (k.length >= 3 && q.includes(k)))) names.push(x.dist[1] + " (জেলা)");
    });
    const uniq = Array.from(new Set(names)).slice(0, 6);
    if (uniq.length) {
      return { msg: "🤔 \"" + query + "\" নামে সরাসরি পাইনি। আপনি কি বুঝিয়েছেন:\n" + uniq.map((n) => "• " + n).join("\n"), reply: null };
    }
  }

  return {
    msg: "❌ \"" + query + "\" নামে কোনো বিভাগ, জেলা বা জায়গা পাইনি।\n💡 সঠিক নাম লিখুন, যেমন: .maps সিলেট\nসব বিভাগ দেখতে শুধু .maps লিখুন।",
    reply: null
  };
}

// মেসেজ পাঠানো + রিপ্লাই ট্র্যাক করা (যাতে নম্বর রিপ্লাই দিলে কাজ করে)
function send(api, event, out) {
  return api.sendMessage(
    out.msg,
    event.threadID,
    (err, info) => {
      if (err || !info || !out.reply) return;
      try {
        global.client.handleReply.push(
          Object.assign({ name: module.exports.config.name, messageID: info.messageID, author: event.senderID }, out.reply)
        );
      } catch (e) {}
    },
    event.messageID
  );
}

module.exports.run = async function ({ api, event, args }) {
  if (!_creditOk()) return api.sendMessage(_CREDIT_MSG, event.threadID, event.messageID);
  try {
    const a = args || [];
    // সরাসরি: .maps রংপুর ৩
    if (a.length > 1 && /^[0-9০-৯]+$/.test(a[a.length - 1])) {
      const n = Number(enNum(a[a.length - 1]));
      const hit = findDistrict(norm(a.slice(0, -1).join(" ")));
      if (hit && n >= 1 && n <= hit.dist[3].length) {
        return send(api, event, { msg: placeCard(hit.dist[3][n - 1], hit.dist, hit.div), reply: null });
      }
    }
    return send(api, event, buildAnswer(a.join(" ")));
  } catch (e) {
    console.log("[maps] error:", e && e.message ? e.message : e);
    return api.sendMessage("❌ কিছু একটা সমস্যা হয়েছে, আবার চেষ্টা করুন।", event.threadID, event.messageID);
  }
};

// নম্বর রিপ্লাই: বিভাগ → জেলা → জায়গা (গুগল ম্যাপ লিংক)
module.exports.handleReply = async function ({ api, event, handleReply }) {
  if (!_creditOk()) return api.sendMessage(_CREDIT_MSG, event.threadID, event.messageID);
  try {
    if (handleReply.author && String(handleReply.author) !== String(event.senderID)) return;
    const nums = (enNum(event.body || "").match(/\d+/g) || []).map(Number);
    if (!nums.length) return;
    const div = DIVISIONS[handleReply.div];

    if (handleReply.type === "overview") {
      const d = DIVISIONS[nums[0] - 1];
      if (!d) return send(api, event, { msg: "❌ ১ থেকে " + bnNum(DIVISIONS.length) + " এর মধ্যে নম্বর লিখুন।", reply: null });
      return send(api, event, divisionAnswer(d));
    }
    if (handleReply.type === "division") {
      const x = div.districts[nums[0] - 1];
      if (!x) return send(api, event, { msg: "❌ ১ থেকে " + bnNum(div.districts.length) + " এর মধ্যে নম্বর লিখুন।", reply: null });
      return send(api, event, districtAnswer(div, x, false));
    }
    if (handleReply.type === "district") {
      const dist = div.districts[handleReply.dist];
      const picks = Array.from(new Set(nums)).filter((n) => n >= 1 && n <= dist[3].length).slice(0, 5);
      if (!picks.length) return send(api, event, { msg: "❌ ১ থেকে " + bnNum(dist[3].length) + " এর মধ্যে নম্বর লিখুন।", reply: null });
      return send(api, event, { msg: picks.map((n) => placeCard(dist[3][n - 1], dist, div)).join("\n\n"), reply: null });
    }
  } catch (e) {
    console.log("[maps] reply error:", e && e.message ? e.message : e);
  }
};

